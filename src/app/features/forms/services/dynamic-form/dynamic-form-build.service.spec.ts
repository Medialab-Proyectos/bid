import { UntypedFormBuilder, UntypedFormGroup } from '@angular/forms';

describe('DynamicFormBuildService', () => {
  let service: DynamicFormBuildService;
  let http: HttpRequestController;

  beforeEach(() => {
    TestBed.configureTestingModule({
      imports: [ReactiveFormsModule, FormsModule, HttpClientTestingModule],
      providers: [HttpRequestController],
    });
    service = TestBed.inject(DynamicFormBuildService);
    http = TestBed.inject(HttpRequestController);
  });

  it('should be created', () => {
    expect(service).toBeTruthy();
  });

  it('call getDynamicForm', () => {
    const basePath = `${environment.hostApi.fiduciaryProcessApi.endpoint}/api/`;
    const type = 'SPN-MINOR-WORKS';
    const operationNumber = 'UR-L1111';
    const language = 'en';
    const biddingProcessProcurementProcessId =
      '50e2d370-41e6-4e73-b987-4d0eaeffd17f';

    service
      .getDynamicForm(
        type,
        operationNumber,
        language,
        biddingProcessProcurementProcessId
      )
      .subscribe((response) => {
        expect(response).toEqual(responseMock);
      });

    const url = `${basePath}biddingDocuments/forms?type=${type}&operationNumber=${operationNumber}&language=${language}&biddingProcessProcurementProcessId=${biddingProcessProcurementProcessId}`;
    http.mockRequest(url, 'get', responseMock);
  });

  it('call generateForm', () => {
    const fb: UntypedFormBuilder = new UntypedFormBuilder();
    const dynamicForm: UntypedFormGroup = fb.group({});
    service.generateForm(responseMock, dynamicForm, 0);
  });
});

