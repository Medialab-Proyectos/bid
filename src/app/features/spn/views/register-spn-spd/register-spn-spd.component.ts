  createSpn(): void {
    this.allLoaded = false;
    this.procurementNoticesSvc
      .createSpn(this.mapRequest(this.spnForm))
      .subscribe({
        next: (data) => {
          this.allLoaded = true;
          const message = this.translateService.instant(
            'UNDB.SPN.FORM.SUCCESFUL_REGISTRATION'
          );
          this.globalNotificationService.showSuccess(message);
          this.goToPreview(data);
        },
        error: (err: HttpErrorResponse) => {
          const e = err.error as ErrorResponseValidations;
          const errorDetails = e.errors?.[0]?.description || '';
          const errorMessage =
            e.detail + (errorDetails ? '\n' + errorDetails : '');
          this.globalNotificationService.showError(errorMessage);
          this.allLoaded = true;
        },
      });
  }

  updateSpn(): void {
    const noticeId = this.route.snapshot.params.noticeId;
    this.allLoaded = false;
    this.procurementNoticesSvc
      .updateSpn(this.mapRequest(this.spnForm), noticeId)
      .subscribe({
        next: (_data) => {
          this.allLoaded = true;
          const message = this.translateService.instant(
            'UNDB.SPN.FORM.SUCCESFUL_UPDATE'
          );
          this.globalNotificationService.showSuccess(message);
          this.goToPreview(noticeId);
        },
        error: (err: HttpErrorResponse) => {
          const e = err.error as ErrorResponseValidations;
          const errorDetails = e?.errors[0]?.description;
          this.globalNotificationService.showError(
            e.detail + '\n' + errorDetails
          );
          this.allLoaded = true;
        },
      });
  }

  goToPreview(noticeId: string): void {
    this.router.navigate(['../../', noticeId, 'preview'], {
      relativeTo: this.route,
    });
  }

  goBack() {
    this.router.navigate(['../../../../..'], { relativeTo: this.route });
  }

