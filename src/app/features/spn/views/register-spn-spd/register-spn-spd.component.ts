  onExit() {
    if (!this.spnForm.dirty) {
      this.goBack();
      return;
    }
    const dialogData: ConfirmCancelDialogData = {
      headerIcon: 'info',
      headerEnum: 'UNDB.FORM.EXIT_DIALOG.HEADER',
      bodyTextEnum: 'UNDB.FORM.EXIT_DIALOG.BODY',
      cancelButtonEnum: 'ANT_TRANSACTION.CANCEL',
      confirmButtonEnum: 'UNDB.FORM.EXIT_DIALOG.CONFIRM_BTN',
    };

    if (this.isEditRoute()) {
      dialogData.bodyTextEnum = 'UNDB.FORM.EXIT_DIALOG.EDIT_EOI.BODY';
      dialogData.headerEnum = 'UNDB.FORM.EXIT_DIALOG.EDIT_EOI.HEADER';
    }

    const dialog = this.matDialogService.open(ConfirmCancelDialogComponent, {
      data: dialogData,
    });

    dialog
      .afterClosed()
      .pipe(
        tap((res) => {
          if (res) {
            this.goBack();
          }
        })
      )
      .subscribe();
  }

