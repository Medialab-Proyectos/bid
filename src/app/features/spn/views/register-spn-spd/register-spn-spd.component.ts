  onSpnTypeChange(type: MatSelectChange) {
    if (!this.isEditRoute()) {
      this.router.navigate(['../', type.value.toLowerCase()], {
        relativeTo: this.route,
      });
    } else {
      const dialogData: ConfirmCancelDialogData = {
        headerIcon: 'info',
        headerEnum: 'SPN.CHANGE_NOTICE_TYPE_MODAL.HEADER',
        bodyTextEnum: 'SPN.CHANGE_NOTICE_TYPE_MODAL.BODY',
        cancelButtonEnum: 'SPN.CHANGE_NOTICE_TYPE_MODAL.CANCEL',
        confirmButtonEnum: 'SPN.CHANGE_NOTICE_TYPE_MODAL.CONFIRM',
      };
      const dialog = this.matDialogService.open(ConfirmCancelDialogComponent, {
        data: dialogData,
      });

      dialog
        .afterClosed()
        .pipe(
          tap((res) => {
            if (res) {
              this.spnSvc.isSDPNotice = type.value === 'SDP';
              this.reloadOnChangeType(type);
            } else {
              const previousValue =
                this.spnForm.controls.spnType.getRawValue() === 'SDP'
                  ? 'SDO'
                  : 'SDP';
              this.spnForm.controls.spnType.setValue(previousValue, {
                emitEvent: false,
              });
              this.spnForm.controls.spnType.markAsPristine();
            }
          })
        )
        .subscribe();
    }
  }

  reloadOnChangeType(type) {
    this.allLoaded = false;
    this.isSDP = type.value.toLowerCase() === 'sdp';
    setTimeout(() => {
      this.allLoaded = true;
      this.initializeForm();
      this.listenAccompanimentChanges();
      this.listenSameOpeningAddressChangess();
      this.listenToBidSecurityOptionChanges(BidSecurityOptions.AMOUNT);
      this.spnForm.controls.typeOfAccompaniment.setValue(
        AccompanimentOptions.GUARANTEE
      );
      this.spnForm.controls.bidSecurityOption.setValue(
        BidSecurityOptions.AMOUNT
      );
      this.sameOpeningAddressUpdate(MatchingDirectionOptions.SAME);
      this.spnForm.controls.recipient.controls.executingAgency.setValue(
        this.projectInfo.executor
      );
      this.spnForm.controls.projectName.setValue(
        this.projectInfo.projectName || this.projectNameEn
      );
      this.noLots = true;
      this.spnForm.controls.worksToBeAcquired.setValidators([
        Validators.required,
      ]);
      this.spnForm.controls.timeUnit.setValidators([Validators.required]);
      this.spnForm.controls.timeQuantity.setValidators([Validators.required]);
      this.listenLotsChanges();
      this.prepareDataPreview();
    }, 1000);
  }

  convertUtcToLocalDate(utcDate: string): Date {
    return new Date(utcDate + 'Z');
  }

  isEditRoute(): boolean {
    return this.router.url.includes('/update');
  }

  onBidSecurityOptionChange(selectedBidSecurityOption: BidSecurityOptions) {
    const {
      currency,
      amountInCurrency,
      percentageOfBidPrice,
      typeOfAccompaniment,
    } = this.spnForm.controls;

    if (typeOfAccompaniment.value === AccompanimentOptions.MAINTENANCE) {
      currency.disable();
      amountInCurrency.disable();
      percentageOfBidPrice.disable();
      return;
    }

    if (selectedBidSecurityOption === this.bidSecurityOptions.AMOUNT) {
      currency.enable();
      amountInCurrency.enable();
      currency.setValidators(Validators.required);
      amountInCurrency.setValidators(Validators.required);
      percentageOfBidPrice.disable();
      percentageOfBidPrice.reset();

      return;
    }

    currency.disable();
    amountInCurrency.disable();
    currency.reset();
    amountInCurrency.reset();
    percentageOfBidPrice.enable();
    percentageOfBidPrice.setValidators([
      Validators.min(0),
      Validators.max(100),
      Validators.required,
    ]);

    currency.updateValueAndValidity();
    amountInCurrency.updateValueAndValidity();
    percentageOfBidPrice.updateValueAndValidity();
  }

  toggleBidGuaranteeControls(typeOfAccompaniment: string) {
    const {
      currency,
      amountInCurrency,
      percentageOfBidPrice,
      bidSecurityOption,
    } = this.spnForm.controls;

    if (typeOfAccompaniment === AccompanimentOptions.GUARANTEE) {
      bidSecurityOption.enable();

      if (bidSecurityOption.value === BidSecurityOptions.AMOUNT) {
        currency.enable();
        amountInCurrency.enable();
        percentageOfBidPrice.disable();
      } else {
        currency.disable();
        amountInCurrency.disable();
        percentageOfBidPrice.enable();
      }
    } else {
      currency.disable();
      amountInCurrency.disable();
      percentageOfBidPrice.disable();
      bidSecurityOption.disable();
    }

    currency.updateValueAndValidity();
    amountInCurrency.updateValueAndValidity();
    percentageOfBidPrice.updateValueAndValidity();
    bidSecurityOption.updateValueAndValidity();
  }

